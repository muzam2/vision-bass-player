#!/usr/bin/env bash
# Copies the parts of chiaki-ng that Bass Player's Remote Play mode needs into
# Vendor/ChiakiCore/vendor: the protocol core (lib/), nanopb, jerasure, gf-complete and the
# nanopb-generated takion.pb.{c,h}. PSN-only code (holepunch, AIA/curl, FFmpeg/Pi decoders)
# is left out; Sources/ChiakiCore/stubs replaces it. Re-run to bump upstream:
#   tools/vendor_chiaki.sh /path/to/chiaki-ng   (a checkout with submodules initialised)
# Needs python3 with grpcio-tools (for protoc). Records the commits in UPSTREAM.
set -euo pipefail
SRC=${1:?usage: vendor_chiaki.sh /path/to/chiaki-ng}
HERE=$(cd "$(dirname "$0")/.." && pwd)
DST="$HERE/Vendor/ChiakiCore/vendor"
rm -rf "$DST"; mkdir -p "$DST"/{chiaki/src/remote,chiaki/include,proto,nanopb,jerasure,gf-complete}

cp -R "$SRC/lib/include/chiaki" "$DST/chiaki/include/"
rm -f "$DST/chiaki/include/chiaki/"{ffmpegdecoder.h,pidecoder.h,config.h}
cat > "$DST/chiaki/include/chiaki/config.h" <<'H'
// SPDX-License-Identifier: LicenseRef-AGPL-3.0-only-OpenSSL
// Generated by tools/vendor_chiaki.sh (stands in for lib/config.h.in).
#ifndef CHIAKI_CONFIG_H
#define CHIAKI_CONFIG_H
#define CHIAKI_LIB_ENABLE_OPUS 1
#define CHIAKI_LIB_ENABLE_PI_DECODER 0
#define CHIAKI_LIB_ENABLE_FFMPEG_DECODER 0
#endif
H

for f in "$SRC"/lib/src/*.c "$SRC"/lib/src/*.h; do
  case "$(basename "$f")" in
    aia.c|aia_openssl.c|ffmpegdecoder.c|pidecoder.c) continue ;;
  esac
  cp "$f" "$DST/chiaki/src/"
done
# common.c includes "aia.h" for chiaki_aia_init(); AIA only serves PSN's TLS (curl), so the
# header is replaced by a two-function one and stubs/aia_stub.c implements it.
cat > "$DST/chiaki/src/aia.h" <<'H'
// Bass Player: stands in for chiaki-ng's lib/src/aia.h (PSN-only, needs curl). See stubs/.
#ifndef CHIAKI_AIA_H
#define CHIAKI_AIA_H
#include <chiaki/common.h>
ChiakiErrorCode chiaki_aia_init(void);
void chiaki_aia_fini(void);
#endif
H
cp "$SRC/lib/src/remote/rudp.c" "$SRC/lib/src/remote/rudpsendbuffer.c" "$DST/chiaki/src/remote/"
# base64.c / ecdh.c clash with OpenSSL object names in a static link; give them unique names.
mv "$DST/chiaki/src/base64.c" "$DST/chiaki/src/chiaki_base64.c"
mv "$DST/chiaki/src/ecdh.c" "$DST/chiaki/src/chiaki_ecdh.c"

for p in "$HERE"/Vendor/ChiakiCore/patches/*.patch; do
  [ -e "$p" ] || continue
  patch -s -p1 -d "$DST/chiaki" < "$p"
done

TMP=$(mktemp -d)
python3 -m grpc_tools.protoc -o "$TMP/takion.pb" -I"$SRC/lib/protobuf" "$SRC/lib/protobuf/takion.proto"
( cd "$TMP" && python3 "$SRC/third-party/nanopb/generator/nanopb_generator.py" -q takion.pb )
cp "$TMP/takion.pb.c" "$TMP/takion.pb.h" "$DST/proto/"
rm -rf "$TMP"

cp "$SRC"/third-party/nanopb/{pb.h,pb_common.c,pb_common.h,pb_decode.c,pb_decode.h,pb_encode.c,pb_encode.h,LICENSE.txt} "$DST/nanopb/"
mkdir -p "$DST/jerasure/src" "$DST/jerasure/include" "$DST/gf-complete/src" "$DST/gf-complete/include"
cp "$SRC"/third-party/jerasure/src/{galois.c,jerasure.c,reed_sol.c,cauchy.c,liberation.c} "$DST/jerasure/src/"
cp "$SRC"/third-party/jerasure/include/*.h "$DST/jerasure/include/"
cp "$SRC"/third-party/jerasure/{COPYING,License.txt} "$DST/jerasure/"
cp "$SRC"/third-party/gf-complete/src/{gf.c,gf_wgen.c,gf_w4.c,gf_w8.c,gf_w16.c,gf_w32.c,gf_w64.c,gf_w128.c,gf_rand.c,gf_general.c,gf_cpu.c} "$DST/gf-complete/src/"
cp "$SRC"/third-party/gf-complete/include/*.h "$DST/gf-complete/include/"
cp "$SRC"/third-party/gf-complete/{COPYING,License.txt} "$DST/gf-complete/"
cp "$SRC/COPYING" "$DST/chiaki/COPYING"
cp -R "$SRC/LICENSES" "$DST/chiaki/LICENSES"

{
  echo "chiaki-ng   $(git -C "$SRC" rev-parse HEAD)  https://github.com/streetpea/chiaki-ng"
  for s in nanopb jerasure gf-complete; do
    echo "$s $(git -C "$SRC/third-party/$s" rev-parse HEAD)"
  done
} > "$HERE/Vendor/ChiakiCore/UPSTREAM"
echo "vendored into $DST"
